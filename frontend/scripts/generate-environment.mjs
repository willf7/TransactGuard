import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const frontendRoot = new URL('../', import.meta.url);

try {
  process.loadEnvFile(fileURLToPath(new URL('.env', frontendRoot)));
} catch (error) {
  if (error.code !== 'ENOENT') throw error;
}

const primeNgLicenseKey = process.env.PRIMENG_LICENSE_KEY;
if (!primeNgLicenseKey?.trim()) {
  throw new Error('Set PRIMENG_LICENSE_KEY in frontend/.env or the process environment.');
}

const environmentDirectory = new URL('src/environments/', frontendRoot);
mkdirSync(environmentDirectory, { recursive: true });
writeFileSync(
  new URL('environment.generated.ts', environmentDirectory),
  '// Generated by scripts/generate-environment.mjs. Do not edit or commit.\n' +
    `export const environment = ${JSON.stringify({ primeNgLicenseKey })} as const;\n`,
  { mode: 0o600 },
);
